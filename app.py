"""劳动合同自检 · 网页版。

跑法：streamlit run app.py
只在本机跑，文件不上传任何服务器，不调用任何外部接口。
"""

from pathlib import Path

import streamlit as st

from rules_number import 跑全部
from scan import RULES, check_item, extract_salary, read_blocks, 是中文文档

st.set_page_config(page_title="劳动合同自检", page_icon="📄", layout="wide")

st.title("📄 劳动合同自检")
st.caption("HR 自检用。工具只做初筛，**全部结论需法务复核**。")

# 免责放在最上面，不折叠 —— 这不是客套，是这类工具的诚实底线
st.warning(
    "**「未检索到」不等于合同里没有这一条。**　"
    "关键词匹配认不出所有写法（Blair & Maron 1985 实测：律师用关键词检索法律文书，"
    "自认为找到 75%，实际只有 20%）。所以本工具只报「未检索到」，不报「缺失」。"
)

上传 = st.file_uploader("选一份劳动合同（.docx）", type=["docx"])

# 自带样本入口：让人不用先去找文件就能看到工具在干什么。
# 三份是成对的对照组，不是凑数量 —— 见 样本来源.md。
样本 = {
    "（不用样本，我自己传）": None,
    "模拟·违法样本 —— 三条数字规则各踩一个雷": "模拟-违法样本.docx",
    "模拟·合规样本 —— 数字都在法定范围内": "模拟-合规样本.docx",
    "模拟·缺条款样本 —— 只有必备项，无 IP/交接/竞业": "模拟-缺条款样本.docx",
    "真实·宿州人社局劳动合同（通用）": "模板/宿州-劳动合同通用.docx",
}
选的 = st.selectbox("或者直接拿自带样本试试", list(样本.keys()))

来源 = 上传 if 上传 is not None else (样本[选的] and Path(样本[选的]))
if 来源 is None:
    st.info("上面选一份自带样本，或者自己传一份 .docx。")
    st.stop()
if not 上传:
    st.caption(f"正在看自带样本：`{来源}`")

blocks = read_blocks(来源)
全文 = "\n".join(t for _, t in blocks if t)
st.success(f"读到 {len(blocks)} 块（正文段落 + 表格行）")

if not 是中文文档(blocks):
    st.error("⛔ 这份文档不是中文，而本工具的词表是中文的。下面的结果只说明词表匹配不上，不说明合同缺条款。")
    st.stop()

# ============================================================
# 一、数字规则 —— 放最前面，因为这一段的结论是确定的
# ============================================================
st.header("一、数字规则")
st.caption("法律写死了上限，比大小就能定。这一段的结论不依赖语义判断。")

for 名, 结论, 说明, 法条 in 跑全部(全文):
    if 结论 == "违法":
        st.error(f"**{名}｜违法**　\n{说明}　\n\n依据：{法条}")
    elif 结论 == "合规":
        st.success(f"**{名}｜合规**　\n{说明}　\n\n依据：{法条}")
    else:
        st.info(f"**{名}｜信息不足**　\n{说明}　\n\n依据：{法条}")

# ============================================================
# 二、劳动报酬
# ============================================================
st.header("二、劳动报酬")
状态, 证据 = extract_salary(blocks)

if 状态 == "有金额":
    st.success(f"**已填写**（找到 {len(证据)} 处）")
elif 状态 == "金额留空":
    st.warning("**有工资条款，但金额位置是空的** —— 合同没填工资，这是要退回的")
else:
    st.error("**未检索到工资条款**")

for pos, 值, 原文 in 证据[:5]:
    st.markdown(f"　`{pos}`　**{值}**　　{原文[:80]}")

# ============================================================
# 三、条款有无
# ============================================================
st.header("三、条款有无")
st.caption("关键词匹配，业界实测 F1 约 0.6（LEDGAR, LREC 2020）。只用来定位，不下结论。")

for 项名, rule in RULES.items():
    状态, 证据 = check_item(blocks, rule)
    图标 = {"已检索到": "✅", "待确认": "❓", "未检索到": "—"}[状态]

    with st.expander(f"{图标}　{项名}　—　{状态}（{len(证据)} 处）", expanded=(状态 == "待确认")):
        if not 证据:
            st.markdown("本工具的词表没有匹配到。**这不代表合同里没有**，请人工确认。")
        for pos, 原文, 主词, 弱化 in 证据:
            if 弱化:
                st.markdown(
                    f"`{pos}`　命中「{主词}」　⚠️ **带弱化词：{'/'.join(弱化)}**　"
                    "——「可以另行协商签订」不是约定，是把事情推给了另一份文件"
                )
            else:
                st.markdown(f"`{pos}`　命中「{主词}」")
            st.markdown(f"> {原文}")
