"""扫描一份 .docx 劳动合同，检查关键条款齐不齐。

产出给法务做二次审核用：哪些条款有、哪些缺、原文在哪。
工具只做初筛，不下最终判断。
"""

import re
import sys

from docx import Document


# ============================================================
# ① 读取：把 .docx 读成 [(位置, 文本), ...]
# ============================================================
def read_blocks(path):
    """位置是给人看的定位串，例如「第12段」「表1 行2列3」。

    正文段落和表格单元格都要读 —— 劳动合同很爱把薪资排进表格，
    而 doc.paragraphs 是不含表格的，只读它会安静地漏掉一整块内容。
    """
    doc = Document(path)
    blocks = []

    for i, p in enumerate(doc.paragraphs):
        blocks.append((f"第{i}段", p.text.strip()))

    # 表格按「行」读，不按单元格读。
    # 因为表格是拿左格放标签、右格放值的：「基本工资 | 9000 元/月」。
    # 拆成两块，「工资」和「9000元」就永远碰不到一起，薪资照样提不出来。
    for t, table in enumerate(doc.tables, 1):
        for r, row in enumerate(table.rows, 1):
            cells, seen = [], set()
            for cell in row.cells:
                # 合并单元格会让同一个格子在这里出现好几次，去重
                if id(cell._tc) in seen:
                    continue
                seen.add(id(cell._tc))
                cells.append(cell.text.strip())
            blocks.append((f"表{t} 行{r}", " | ".join(cells)))

    return blocks


# ============================================================
# ② 规则表：加检查项只动这里，不动下面的逻辑
# ============================================================
# 每项三组词，各管一件事：
#   主词   —— 这段话在谈这个话题吗
#   确认词 —— 谈到了，但真的做出约定了吗（"归…所有" vs 只是提了一嘴）
#   弱化词 —— 出现就降级：「可以另行协商签订」不是约定，是把事情推给了另一份文件
RULES = {
    "工作交接": {
        "主词": ["交接", "移交", "归还", "退还"],
        "确认词": ["办理", "手续", "应当", "负责", "完成"],
        "弱化词": ["可以", "另行", "参照", "另订", "另签"],
    },
    "知识产权归属": {
        "主词": ["知识产权", "职务发明", "职务作品", "专利", "著作权", "技术成果", "研究成果"],
        "确认词": ["归", "属于", "所有", "享有", "归属"],
        "弱化词": ["可以", "另行", "协商约定", "另订", "另签", "参照"],
    },
    "保密义务": {
        "主词": ["保密", "商业秘密", "机密"],
        "确认词": ["应当", "不得", "义务", "负有", "承担"],
        "弱化词": ["可以", "另行", "另订", "另签"],
    },
    "竞业限制": {
        "主词": ["竞业限制", "竞业禁止"],
        "确认词": ["补偿", "期限", "不得", "月"],
        "弱化词": ["可以", "另行", "协商约定", "另订", "另签"],
    },
}


# ============================================================
# ③ 检查一项，返回三态
# ============================================================
def check_item(blocks, rule):
    """三态：
       命中     —— 主词和确认词都在同一段里，且没有弱化词
       待确认   —— 只有主词，或者虽然齐全但带着弱化词（例如「可以另行签订协议」）
       未命中   —— 主词一个都没出现

    为什么要「待确认」这一档：二值的「有/无」会让人看到打勾就跳过原文，
    而原文才是有用的那部分。实测踩过——「涉及知识产权的保密事项，甲方可以与乙方
    协商约定并签订协议」命中了「知识产权」，但它根本没约定归属。
    """
    strong, weak = [], []

    for pos, text in blocks:
        if not text:
            continue
        hit_main = [w for w in rule["主词"] if w in text]
        if not hit_main:
            continue

        hit_sure = [w for w in rule["确认词"] if w in text]
        hit_weak = [w for w in rule["弱化词"] if w in text]

        record = (pos, text, hit_main[0], hit_weak)
        if hit_sure and not hit_weak:
            strong.append(record)
        else:
            weak.append(record)

    if strong:
        return "已检索到", strong
    if weak:
        return "待确认", weak
    return "未检索到", []


# ============================================================
# ④ 薪资单独处理 —— 它是「提取一个值」，不是「定位一段话」
# ============================================================
# 用同一套定位逻辑处理薪资，会在长合同里捞回十几段噪音
# （「带薪年休假」命中「薪」、「社保从工资中代扣」命中「工资」）。
# 所以这一项走正则提金额。

金额 = re.compile(r"(\d[\d,，]*(?:\.\d+)?)\s*(万)?\s*元")
留空 = re.compile(r"[\s　_＿．\.]{2,}元")          # 「月工资      元」这种没填的
周期 = re.compile(r"每?\s*(月|小时|天|日|年|周)")
薪资词 = ["工资", "薪酬", "月薪", "报酬", "计酬"]
排除词 = ["带薪", "社会保险", "代扣", "个人所得税", "加班工资", "最低工资"]


def extract_salary(blocks):
    """返回 (状态, 证据列表)。
       有金额     —— 提到了工资并且写了具体数字
       金额留空   —— 有工资条款，但数字位置是空的（合同没填，这对 HR 是真问题）
       未提及     —— 压根没有工资条款
    """
    有金额, 留空的 = [], []

    for pos, text in blocks:
        # 按句子切开再判断。
        # 整段判断会出事：「…支付乙方工资。工资为每月　　元。…按规定支付加班工资。」
        # 这一段里既有要找的「工资为每月＿元」，也有该排除的「加班工资」，
        # 整段剔除等于把要找的那句一起扔了。（实测踩过，武汉简易那份。）
        for 句 in re.split(r"[。；;\n]", text):
            if not any(w in 句 for w in 薪资词):
                continue
            if any(w in 句 for w in 排除词):
                continue

            m = 金额.search(句)
            if m:
                单位 = "万元" if m.group(2) else "元"
                p = 周期.search(句)
                周 = f"/{p.group(1)}" if p else ""
                有金额.append((pos, f"{m.group(1)}{单位}{周}", 句))
            elif 留空.search(句):
                留空的.append((pos, "（未填写）", 句))

    if 有金额:
        return "有金额", 有金额
    if 留空的:
        return "金额留空", 留空的
    return "未检索到", []


# ============================================================
# ⑤ 语言粗判：词表是中文的，英文合同全项落空是「词表不通」，不是「合同真缺」
# ============================================================
def 是中文文档(blocks):
    text = "".join(t for _, t in blocks)
    if not text:
        return True
    汉字数 = sum(1 for ch in text if "一" <= ch <= "鿿")
    return 汉字数 / len(text) > 0.10


# ============================================================
# ⑥ 跑起来
# ============================================================
# 措辞是有讲究的，不要改回「缺」。
# Blair & Maron 1985 实测：律师用关键词检索法律文书，自认为找到了 75%，
# 实际只有 20% —— 人穷举不完同一件事的所有说法。
# 所以「没找到」只能说成「未检索到」，不能说成「缺失」：
# 后者是事实结论，会让 HR 去补一条合同里本来就有、只是换了说法的条款。
标记 = {"已检索到": "[已检索到]", "待确认": "[待确认]", "未检索到": "[未检索到]",
        "有金额": "[已检索到]", "金额留空": "[金额未填]"}

免责 = ("⚠ 本工具只做初筛，结论需法务复核。\n"
        "  「未检索到」不等于合同里没有 —— 可能只是换了个说法，本工具认不出。")


def main(path):
    blocks = read_blocks(path)
    print(f"文件：{path}")
    print(f"读到 {len(blocks)} 块（正文段落 + 表格单元格）")
    print(免责 + "\n")

    if not 是中文文档(blocks):
        print("⛔ 这份文档不是中文，而本工具的词表是中文的。")
        print("   下面的结果只说明「中文词表匹配不上」，不说明这份合同缺条款。\n")

    状态, 证据 = extract_salary(blocks)
    print(f"{标记[状态]:8} 劳动报酬 —— {状态}")
    for pos, 值, 原文 in 证据[:2]:
        print(f"         {pos}　{值}　| {原文[:52]}")

    for 项名, rule in RULES.items():
        状态, 证据 = check_item(blocks, rule)
        print(f"\n{标记[状态]:8} {项名} —— {状态}（{len(证据)} 处）")
        for pos, 原文, 主词, 弱化 in 证据[:2]:
            尾 = f"　⚠弱化词：{'/'.join(弱化)}" if 弱化 else ""
            print(f"         {pos}　[{主词}]{尾}")
            print(f"         {原文[:60]}")


if __name__ == "__main__":
    main(sys.argv[1])
