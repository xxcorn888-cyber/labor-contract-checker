"""数字规则：不是「有没有这条」，而是「这几个数合不合法」。

和 scan.py 的关键词匹配是两类活：
  关键词匹配 —— 找条款在哪，业界实测 F1 大约 0.6，只能给「待确认」
  数字规则   —— 比大小，法律写死了上限，答案是确定的

所以这一类才是这个工具真正硬的地方。
法条依据全部写在规则里，输出时一起打出来，让法务能核。
"""

import re

# ------------------------------------------------------------
# 中文数字 → 阿拉伯数字（合同里「三个月」和「3个月」都常见）
# ------------------------------------------------------------
中文数 = {"零": 0, "一": 1, "二": 2, "两": 2, "三": 3, "四": 4, "五": 5,
          "六": 6, "七": 7, "八": 8, "九": 9, "十": 10}


def 读数(s):
    """把「3」「三」「十二」「一年半」里的数字部分读成整数，读不出来返回 None。"""
    s = s.strip()
    if s.isdigit():
        return int(s)
    if s == "十":
        return 10
    if "十" in s:                      # 十二 / 二十 / 二十四
        左, _, 右 = s.partition("十")
        return (中文数.get(左, 1) if 左 else 1) * 10 + (中文数.get(右, 0) if 右 else 0)
    return 中文数.get(s)


数字 = r"(\d+|[一二两三四五六七八九十]+)"


# ------------------------------------------------------------
# 从合同文本里抠出「合同期限」和「试用期」，单位统一成月
# ------------------------------------------------------------
合同期_年月日 = re.compile(
    r"(\d{4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日\s*起.{0,6}?"
    r"(\d{4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日\s*止")
合同期_时长 = re.compile(r"合同期限?为?\s*" + 数字 + r"\s*(年|个月)")
无固定期限 = re.compile(r"无固定期限")
完成任务为期限 = re.compile(r"以完成一定工作任务为期限")
试用期_时长 = re.compile(r"试用期(?:为|从|自)?[^。；]{0,12}?" + 数字 + r"\s*(年|个月)")


def 抽期限(全文):
    """返回 (合同期月数 或 '无固定期限' 或 '完成任务' 或 None, 试用期月数 或 None)。"""
    合同期 = None

    m = 合同期_年月日.search(全文)
    if m:
        y1, m1, d1, y2, m2, d2 = (int(x) for x in m.groups())
        合同期 = (y2 - y1) * 12 + (m2 - m1) + (1 if d2 >= d1 else 0)
    elif 合同期_时长.search(全文):
        m = 合同期_时长.search(全文)
        n = 读数(m.group(1))
        合同期 = n * 12 if n and m.group(2) == "年" else n
    elif 无固定期限.search(全文):
        合同期 = "无固定期限"
    elif 完成任务为期限.search(全文):
        合同期 = "完成任务"

    试用期 = None
    m = 试用期_时长.search(全文)
    if m:
        n = 读数(m.group(1))
        if n is not None:
            试用期 = n * 12 if m.group(2) == "年" else n

    return 合同期, 试用期


# ------------------------------------------------------------
# 规则一：试用期上限（《劳动合同法》第十九条）
# ------------------------------------------------------------
def 查试用期(全文):
    """返回 (结论, 说明, 法条)。结论只有三种：违法 / 合规 / 信息不足。"""
    法条 = "《劳动合同法》第十九条、第八十三条"
    合同期, 试用期 = 抽期限(全文)

    if 试用期 is None:
        return "信息不足", "没有读到试用期长度（可能是留白未填，也可能是本工具没认出写法）", 法条
    if 合同期 is None:
        return "信息不足", f"读到试用期 {试用期} 个月，但没读到合同期限，无法比对上限", 法条

    if 合同期 == "完成任务":
        return "违法", f"以完成一定工作任务为期限的合同**不得约定试用期**，但合同里写了 {试用期} 个月", 法条
    if 合同期 == "无固定期限":
        上限, 档 = 6, "无固定期限"
    elif 合同期 < 3:
        return "违法", f"合同期 {合同期} 个月不满三个月，**不得约定试用期**，但合同里写了 {试用期} 个月", 法条
    elif 合同期 < 12:
        上限, 档 = 1, f"合同期 {合同期} 个月（三个月以上不满一年）"
    elif 合同期 < 36:
        上限, 档 = 2, f"合同期 {合同期} 个月（一年以上不满三年）"
    else:
        上限, 档 = 6, f"合同期 {合同期} 个月（三年以上）"

    if 试用期 > 上限:
        return "违法", f"{档} → 试用期上限 {上限} 个月，合同写的是 **{试用期} 个月**，超了 {试用期 - 上限} 个月", 法条
    return "合规", f"{档} → 上限 {上限} 个月，合同写的是 {试用期} 个月", 法条


# ------------------------------------------------------------
# 规则二：竞业限制期限上限二年（第二十四条）
# ------------------------------------------------------------
竞业期 = re.compile(r"竞业(?:限制|禁止)[^。；]{0,30}?" + 数字 + r"\s*(年|个月)")


def 查竞业期限(全文):
    法条 = "《劳动合同法》第二十四条第二款"
    m = 竞业期.search(全文)
    if not m:
        return "信息不足", "没有读到竞业限制的期限", 法条
    n = 读数(m.group(1))
    if n is None:
        return "信息不足", "读到竞业限制期限但解析不出数字", 法条
    月 = n * 12 if m.group(2) == "年" else n
    if 月 > 24:
        return "违法", f"竞业限制期限 {月} 个月，**超过法定上限 24 个月**", 法条
    return "合规", f"竞业限制期限 {月} 个月，未超过 24 个月上限", 法条


# ------------------------------------------------------------
# 规则三：违约金只能出现在服务期和竞业限制两种情形（第二十五条）
# ------------------------------------------------------------
# 「第四条 违约金」这种条款标题也含关键词，但它不是约定内容。
# 拿它当证据，报出来的句子对不上法务想看的那一句。
标题句 = re.compile(r"^第[一二三四五六七八九十百]+条[\s、:：]*\S{0,10}$")


def 是标题(句):
    return bool(标题句.match(句.strip()))


def 查违约金(全文):
    法条 = "《劳动合同法》第二十二条、第二十三条、第二十五条"
    句子 = [s for s in re.split(r"[。；;\n]", 全文)
            if "违约金" in s and not 是标题(s)]
    if not 句子:
        return "信息不足", "没有读到违约金条款（或只出现在条款标题里）", 法条

    合法语境 = ["服务期", "专项培训", "专业技术培训", "竞业限制", "竞业禁止"]
    越界 = [s for s in 句子 if not any(w in s for w in 合法语境)]
    if 越界:
        return "违法", ("第二十五条只允许在**服务期**和**竞业限制**两种情形约定违约金，"
                        f"下面这句都不沾：「{越界[0][:40]}」"), 法条
    return "合规", f"违约金出现在合法情形中（共 {len(句子)} 处）", 法条


规则表 = [
    ("试用期期限", 查试用期),
    ("竞业限制期限", 查竞业期限),
    ("违约金情形", 查违约金),
]


def 跑全部(全文):
    return [(名, *fn(全文)) for 名, fn in 规则表]
