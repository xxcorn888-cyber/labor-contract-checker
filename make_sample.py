"""生成测试用的模拟劳动合同 .docx。

⚠️ 这些都不是真实合同，是为测试而生成的。

为什么需要它们：公开渠道拿得到的官方示范文本，金额和期限**全是留白**
（「月工资＿＿元」「试用期＿个月」），数字规则在上面一条都测不出来。
所以必须有填了数字的样本。

三份构成一个测试矩阵，是成对的对照组，不是凑数量：
  合规样本 —— 该有的都有、数字都合法  → 期望：全部合规
  违法样本 —— 试用期超期/竞业超2年/违约金越界 → 期望：三条全报违法
  缺条款   —— 只有法定必备项，无 IP/交接/竞业 → 期望：报「未检索到」

模拟数据一律自证是假的：公司名带「测试」、人名「张测试」、
手机用官方保留号段、金额取非整数，避免撞上任何真实主体。
"""

from docx import Document

# ⚠️ 这段标注的措辞是踩过坑改的，别往里加条款名。
# 初版写了「其中知识产权归属条款依据《专利法》第六条拟制」，
# 结果工具在一份根本没有 IP 条款的样本上报出「知识产权归属：已检索到」——
# 命中的正是这句标注本身。测试样本污染了测试结果。
# 拟制依据这类信息挪去同目录 `样本来源.md`，那份不进检测。
标注 = (
    "【测试用模拟文本 · 非真实合同】"
    "本文件由「合同自检」项目生成，仅用于测试，不是任何真实签署过的合同，"
    "不构成法律文本或范本。文中所有单位名称、人员姓名、证件号码、金额、日期均为虚构。"
    "骨架来源与拟制依据见同目录 样本来源.md。生成脚本：make_sample.py"
)


def 起草(doc, 标题, 合同期, 试用期, 条款们, 表格=None):
    doc.add_paragraph(标注)              # 标注放正文第一段：页眉 python-docx 默认读不到
    doc.add_paragraph(标题)
    doc.add_paragraph("甲方（用人单位）：示例科技（测试）有限公司")
    doc.add_paragraph("乙方（劳动者）：张测试　　联系电话：13800000000")
    doc.add_paragraph("")
    doc.add_paragraph("第一条 合同期限")
    doc.add_paragraph(f"本合同为固定期限劳动合同，自{合同期[0]}起至{合同期[1]}止，其中试用期为{试用期}。")
    for i, 正文 in enumerate(条款们, start=2):
        doc.add_paragraph(f"第{'二三四五六七八九十'[i - 2]}条 {正文[0]}")
        doc.add_paragraph(正文[1])
    if 表格:
        doc.add_paragraph("")
        t = doc.add_table(rows=len(表格), cols=2)
        t.style = "Table Grid"
        for row, (a, b) in zip(t.rows, 表格):
            row.cells[0].text, row.cells[1].text = a, b
    doc.add_paragraph("")
    doc.add_paragraph("甲方（盖章）：　　　　　　乙方（签字）：")


# ============================================================
# ① 合规样本：数字都在法定范围内，条款齐全
# ============================================================
doc = Document()
起草(
    doc, "劳动合同书（模拟·合规样本）",
    ("2026年9月1日", "2029年8月31日"),      # 3 年 → 试用期上限 6 个月
    "三个月",                                 # 合法
    [
        ("劳动报酬", "乙方月工资构成见下表，甲方于每月15日以货币形式支付。"),
        ("工作交接", "本合同解除或终止时，乙方应当在离职之日前完成工作交接，"
                     "将其保管的文件、资料、办公用品等移交甲方指定人员。"),
        ("知识产权", "乙方在甲方任职期间完成的职务发明创造、作品及技术秘密，"
                     "其知识产权归甲方所有。"),
        ("保密义务", "乙方应对甲方的商业秘密承担保密义务。"),
        ("竞业限制", "乙方离职后的竞业限制期限为二年，甲方按月支付竞业限制经济补偿。"
                     "乙方违反竞业限制约定的，应当支付违约金。"),
    ],
    表格=[("项目", "金额"), ("基本工资", "8,765 元/月"), ("岗位津贴", "2,340 元/月")],
)
doc.save("模拟-合规样本.docx")

# ============================================================
# ② 违法样本：三条数字规则各踩一个雷
# ============================================================
doc = Document()
起草(
    doc, "劳动合同书（模拟·违法样本）",
    ("2026年9月1日", "2027年8月31日"),      # 1 年 → 试用期上限只有 2 个月
    "六个月",                                 # 🔴 超期 4 个月
    [
        ("劳动报酬", "乙方月工资为 6,540 元，甲方于每月10日支付。"),
        ("竞业限制", "乙方离职后的竞业限制期限为三年。"),          # 🔴 超过 24 个月
        ("违约金", "乙方在合同期内提前离职的，应当向甲方支付违约金 20,000 元。"),  # 🔴 越界
    ],
)
doc.save("模拟-违法样本.docx")

# ============================================================
# ③ 缺条款样本：只有法定必备项，没有 IP / 交接 / 竞业
# ============================================================
doc = Document()
起草(
    doc, "劳动合同书（模拟·缺条款样本）",
    ("2026年9月1日", "2028年8月31日"),      # 2 年 → 上限 2 个月
    "两个月",                                 # 合法
    [
        ("劳动报酬", "乙方月工资为 7,890 元。"),
        ("社会保险", "甲方依法为乙方缴纳社会保险费。"),
        ("工作时间", "甲方安排乙方执行标准工时工作制。"),
    ],
)
doc.save("模拟-缺条款样本.docx")

print("saved: 模拟-合规样本.docx / 模拟-违法样本.docx / 模拟-缺条款样本.docx")
